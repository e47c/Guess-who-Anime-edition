/* =====================================================================
   ANIME DRAFT: role sets, rarity, series power tiers and the rating database.

   HOW THE RATINGS WORK (read before editing a number)
   - Every draftable character is keyed by its AniList character id, so name, picture and
     the fan count come from AniList (packs.json / draft-pop.json), never from here.
   - Scores are 1..100 and measured INSIDE the character's own series, from what the character
     has actually shown (feats in the anime / manga), never from popularity, fame or story role:
       97-100 the series' best in that category (at most 3 characters per category)
       88-96  elite, clearly top-tier feats          75-87 high      55-74 a solid named fighter
       35-54  below average / limited feats          11-34 weak at it      1-10 can't do it at all
   - Each category is judged on its own:
       Strength = physical force (lifting, striking); a destructive POWER belongs in Special.
       Speed = movement, reactions and combat speed.   IQ = intellect, strategy, knowledge (not battle instinct).
       Durability = toughness and defensive abilities; REGENERATION is not durability.
       Combat Skill = technique, experience, weapon mastery.   Special Ability = the signature power itself.
   - One version per character (written in js/draft/basis.js, e.g. "v: Gear 5 (Wano/Egghead)"), the same
     version for all of its numbers. Temporary one-off power-ups (Gon's adult form) are not used.
     Where the canon is thin, the number is conservative and the basis says so.
   - js/draft/basis.js holds the reason for every row and FEATS, the canon comparisons the numbers must
     respect ("STR Edward Newgate > Monkey D. Luffy"). node tools/draft-check.mjs checks them all.
   - A match with two or more series uses the Mixed roles. Physical power (Strength, Speed,
     Durability, and Tank / Duelist in Classic roles) and Special Ability are then multiplied by
     the series' power tier (TIERS below) so Goku and Tanjiro are not treated as equals.
     IQ, Combat Skill, Captain, Vice Captain, Healer and Support are NOT scaled: they are skill
     and character qualities, not raw power. The breakdown on the results screen shows the
     multiplier, so nothing is hidden.
   - Popularity never feeds a rating or a rarity. Rarity (RANKS: power + story importance per series) is a
     separate, visible bonus that never changes a role score.

   ROW FORMAT
   Standard series:  [aniListId, "Name", STR, SPD, IQ, DUR, CMB, SPC, R5, R6, CAP, VC, TANK, DUEL, HEAL, SUP]
       STR/SPD/IQ/DUR = the four shared roles, CMB = Combat Skill and SPC = Special Ability (Mixed roles),
       R5/R6 = the series' two own roles (ROLESETS[key][4..5]), then the six Classic roles.
   Death Note:       [aniListId, "Name", STR, SPD, IQ, DUR, CMB, SPC, INT, DED, MAN, PLA, DEC, PSY, CAP, VC, TANK, DUEL, HEAL, SUP]
   To add a character: find its AniList id (anilist.co/character/<id>), add a row here AND its basis in
   js/draft/basis.js, run `node tools/draft-check.mjs` (validates every row and the canon comparisons)
   and `node tools/draft-sync.mjs` (fetches the picture). Then `node tools/feud-check.mjs`: Feud resolves
   short answers ("Yami", "L") against this roster, and a new name can make one ambiguous.
   ===================================================================== */

