// Anime TCG: writes docs/duel-cards.md, the review table of every card (rarity, ATK, DEF, ability, timing) and
// every Action card, plus each ability's bot-vs-bot win rate. Run: node tools/duel-cards-doc.mjs [games]
import { writeFileSync } from "node:fs";
import { newDuel, act, useDefs } from "../js/duel/engine.js?v=1";
import { botMove } from "../js/duel/bot.js";
import { DEFS, ACTIONS, ACTION_IDS } from "../js/duel/cards.js";
import { CARDS } from "../js/vault/carddb.js";
import { ABILITIES, RARITY_NAMES } from "../js/cardvault/abilities.js";
import { DUEL } from "../js/vault/config.js";

useDefs(DEFS);
const TIMING = { summon: "On summon", attack: "On attack", attacked: "When attacked", destroyed: "When destroyed", cont: "Continuous", opt: "Once per turn" };
const esc = v => String(v == null ? "" : v).replace(/\|/g, "\\|").replace(/\n/g, " ");
const row = cells => "| " + cells.map(esc).join(" | ") + " |";
const ids = Object.keys(CARDS).map(Number);

/* ---- per-ability win rate: random real decks, Normal bots ---- */
const games = Number(process.argv[2]) || 6000;
let seed = 777; const rnd = () => { seed = (seed * 1664525 + 1013904223) >>> 0; return seed / 4294967296; };
const abWin = {}, actWin = {}, rarWin = {};
const bump = (m, k, w) => { m[k] = m[k] || { p: 0, w: 0 }; m[k].p++; m[k].w += w; };
for (let g = 0; g < games; g++) {
    const decks = {};
    [1, 2].forEach(p => { const pick = new Set(); while (pick.size < 16) pick.add(ids[Math.floor(rnd() * ids.length)]); const acts = []; for (let i = 0; i < 4; i++) acts.push("a:" + ACTION_IDS[Math.floor(rnd() * ACTION_IDS.length)]); decks["p" + p] = [...pick].concat(acts); });
    const s = newDuel({ id: "doc" + g, seed: 1 + g * 13, players: [1, 2], decks, names: {}, now: 0, rules: DUEL.rules });
    let steps = 0, now = 0;
    while (!s.over && steps++ < 4000) { now += 1000; const who = s.pending ? Number(s.pending.who) : Number(s.turnP); const m = botMove(s, who, "normal", DEFS, rnd); if (!m || act(s, Object.assign({ by: who }, m), now)) break; }
    if (!s.over) continue;
    [1, 2].forEach(p => {
        const won = Number(s.place["p" + p]) !== 1 ? 0 : Number(s.place["p" + (3 - p)]) === 1 ? 0.5 : 1;     // a tie counts half
        new Set(decks["p" + p].filter(x => typeof x === "number").map(id => CARDS[id].ab)).forEach(ab => bump(abWin, ab, won));
        new Set(decks["p" + p].filter(x => typeof x === "string").map(x => x.slice(2))).forEach(a => bump(actWin, a, won));
        const top = Math.max(...decks["p" + p].filter(x => typeof x === "number").map(id => CARDS[id].r));
        bump(rarWin, top, won);
    });
}
const pct = m => m && m.p ? Math.round(m.w / m.p * 100) + "%" : "—";

/* ---- the document ---- */
const out = [];
out.push("# Anime TCG · card review table", "");
out.push("Generated by `node tools/duel-cards-doc.mjs` (do not edit by hand; re-run after changing `js/cardvault/abilities.js`,");
out.push("`js/duel/cards.js` or the card data). ATK / DEF are the shown values (stored × " + DUEL.rules.statScale + "). Life: " + DUEL.rules.life + " (free-for-all " + DUEL.rules.lifeFfa + ").", "");
out.push("Win rates: " + games + " bot-vs-bot 1v1 duels (Normal bots, random 16-character + 4-Action decks from all " + ids.length + " cards).");
out.push("A healthy ability sits around 45-55%: the share of duels won by decks holding at least one card with it (a tie counts half).", "");
out.push("Contents: [Abilities](#abilities) · [Action cards](#action-cards) · [All cards by series](#all-cards-by-series)", "");

out.push("## Abilities", "");
out.push(row(["Id", "Tier", "Keywords", "Timing", "Text", "Cards", "Win rate"]));
out.push(row(["---", "---", "---", "---", "---", "---:", "---:"]));
const useCount = {}; ids.forEach(id => { useCount[CARDS[id].ab] = (useCount[CARDS[id].ab] || 0) + 1; });
Object.entries(ABILITIES).sort((a, b) => a[1].tier - b[1].tier || a[0].localeCompare(b[0])).forEach(([id, a]) =>
    out.push(row([id, RARITY_NAMES[a.tier], (a.kw || []).join(", "), TIMING[a.t] || a.t, a.text, useCount[id] || 0, pct(abWin[id])])));
out.push("");
out.push("Win rate by the deck's rarest character: " + Object.keys(rarWin).sort().map(r => RARITY_NAMES[r] + " " + pct(rarWin[r])).join(" · ") + ".", "");

out.push("## Action cards", "");
out.push("Up to " + 6 + " per deck, 2 of each; unlocked by player level. Supports are played in your Main phase; Counters are set face-down and answer their trigger once.", "");
out.push(row(["Id", "Name", "Type", "Trigger", "Level", "Text", "Win rate"]));
out.push(row(["---", "---", "---", "---", "---:", "---", "---:"]));
Object.entries(ACTIONS).sort((a, b) => (a[1].type > b[1].type ? -1 : a[1].type < b[1].type ? 1 : a[1].lvl - b[1].lvl)).forEach(([id, a]) =>
    out.push(row([id, a.name, a.type === "counter" ? "Counter" : "Support", a.trig ? ({ attack: "When you are attacked", support: "When an opponent plays a Support", summon: "When an opponent summons" })[a.trig] : "—", a.lvl, a.text, pct(actWin[id])])));
out.push("");

out.push("## All cards by series", "");
const bySeries = {}; ids.forEach(id => { (bySeries[CARDS[id].s] = bySeries[CARDS[id].s] || []).push(CARDS[id]); });
Object.keys(bySeries).sort().forEach(series => {
    const list = bySeries[series].sort((a, b) => String(a.no).localeCompare(String(b.no)));
    out.push("### " + series + " (" + list.length + ")", "");
    out.push(row(["No.", "Name", "Rarity", "Archetype", "ATK", "DEF", "Ability", "Timing", "Text"]));
    out.push(row(["---", "---", "---", "---", "---:", "---:", "---", "---", "---"]));
    list.forEach(c => { const a = ABILITIES[c.ab] || {}; out.push(row([c.no, c.n, RARITY_NAMES[c.r], c.a, c.pow * DUEL.rules.statScale, c.def * DUEL.rules.statScale, c.abName + " (" + c.ab + ")", TIMING[a.t] || a.t, a.text])); });
    out.push("");
});
writeFileSync(new URL("../docs/duel-cards.md", import.meta.url), out.join("\n"));
console.log("docs/duel-cards.md: " + ids.length + " cards, " + Object.keys(ABILITIES).length + " abilities, " + ACTION_IDS.length + " Action cards, " + games + " sim duels");
